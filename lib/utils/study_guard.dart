  /// 家长密码，空字符串表示尚未设置
  static String get parentPassword =>
      GStorage.setting.get(SettingBoxKey.parentPassword, defaultValue: '');

  static bool get hasPassword => parentPassword.isNotEmpty;

  static Future<void> savePassword(String pwd) =>
      GStorage.setting.put(SettingBoxKey.parentPassword, pwd);

  static bool verifyPassword(String input) =>
      hasPassword && parentPassword == input;

  /// 核心判断：该关键词是否允许搜索。
  ///
  /// 采用「包含匹配」而非「完全相等」：
  /// 输入「高中数学 三角函数」能命中词库里的「数学」。
  /// 大小写不敏感，忽略首尾空格。
  static bool allowSearch(String keyword) {
    final String kw = keyword.trim();
    if (kw.isEmpty) return false;

    final List<String> list = whitelist;
    // 词库被清空视为「全部禁止」，防止直接绕过
    if (list.isEmpty) return false;

    final String lower = kw.toLowerCase();
    for (final String item in list) {
      final String rule = item.trim();
      if (rule.isNotEmpty && lower.contains(rule.toLowerCase())) {
        return true;
      }
    }
    return false;
  }
